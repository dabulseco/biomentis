_PASSED: list[str] = []
_FAILED: list[tuple[str, str]] = []


def _check(name: str, cond: bool, detail: str = "") -> None:
    if cond:
        _PASSED.append(name)
        print(f"  ✓ {name}")
    else:
        _FAILED.append((name, detail))
        print(f"  ✗ {name}: {detail}")


class FakeLLM:
    def __init__(self, replies):
        self.replies = list(replies)
        self.calls: list[list] = []

    def invoke(self, messages):
        self.calls.append(list(messages))
        if len(self.calls) > len(self.replies):
            raise AssertionError("an unexpected extra call")
        return SimpleNamespace(content=self.replies[len(self.calls) - 1])


class RaisingLLM:
    def invoke(self, messages):
        raise RuntimeError("boom")


def _reply(code="x = 1\nprint(x)", **over) -> str:
    d = {
        "verdict": "run_with_fixes",
        "issues": [
            {"line": 12, "kind": "bug", "severity": "high", "quote": "np.log(x)", "problem": "ln, not log10", "fix": "np.log10(x)"}
        ],
        "summary": "One bug.",
    }
    if code is not None:
        d["corrected_code"] = code
    d.update(over)
    return json.dumps(d)


