"""Tests for the code review core (request, prompt, tolerant parsing, one retry).

Run with:
    python -m biomentis.agent.tests.test_code_review
"""

from __future__ import annotations

import json
import sys
from types import SimpleNamespace

from biomentis.code_review import (
    CodeReview,
    CodeReviewRequest,
    build_review_messages,
    parse_code_review,
    review_code,
    review_key,
)

_PASSED: list[str] = []
_FAILED: list[tuple[str, str]] = []


def _check(name: str, cond: bool, detail: str = "") -> None:
    if cond:
        _PASSED.append(name)
        print(f"  ✓ {name}")
    else:
        _FAILED.append((name, detail))
        print(f"  ✗ {name}: {detail}")


class FakeLLM:
    def __init__(self, replies):
        self.replies = list(replies)
        self.calls: list[list] = []

    def invoke(self, messages):
        self.calls.append(list(messages))
        if len(self.calls) > len(self.replies):
            raise AssertionError("an unexpected extra call")
        return SimpleNamespace(content=self.replies[len(self.calls) - 1])


class RaisingLLM:
    def invoke(self, messages):
        raise RuntimeError("boom")


def _reply(code="x = 1\nprint(x)", **over) -> str:
    d = {
        "verdict": "run_with_fixes",
        "issues": [
            {"line": 12, "kind": "bug", "severity": "high", "quote": "np.log(x)", "problem": "ln, not log10", "fix": "np.log10(x)"}
        ],
        "summary": "One bug.",
    }
    if code is not None:
        d["corrected_code"] = code
    d.update(over)
    return json.dumps(d)


REQ = CodeReviewRequest(code="import numpy as np\nprint(np.log(5))", task="t")


def test_parse_full_reply():
    r = parse_code_review(_reply())
    _check("parse: verdict", r.verdict == "run_with_fixes", r.verdict)
    _check("parse: one issue at line 12", len(r.issues) == 1 and r.issues[0].line == 12)
    _check("parse: corrected code", r.corrected_code.startswith("x = 1") and not r.error)


def test_parse_normalizes():
    r = parse_code_review(_reply(verdict="maybe", issues=[{"line": 3, "kind": "logic", "severity": "huge", "problem": "p"}]))
    _check("normalize: verdict", r.verdict == "run_with_fixes", r.verdict)
    _check("normalize: kind and severity", r.issues[0].kind == "bug" and r.issues[0].severity == "medium")
    _check("unreadable sets error", parse_code_review("not json").error != "")


def test_retry_once_then_report():
    llm = FakeLLM(["not json", _reply(code=None)])
    r = review_code(llm, REQ, "m")
    _check("retry-once: 2 calls", len(llm.calls) == 2, str(len(llm.calls)))
    _check("retry-once: issues, no script", len(r.issues) == 1 and r.corrected_code == "" and not r.error)


def test_retry_succeeds():
    llm = FakeLLM(["not json", _reply()])
    r = review_code(llm, REQ, "m")
    _check("retry-succeeds: 2 calls and valid", len(llm.calls) == 2 and "x = 1" in r.corrected_code and bool(r.verdict))
    _check("retry message explains", "JSON" in llm.calls[1][-1].content)


def test_syntax_error_retried():
    llm = FakeLLM([_reply(code="def f(:\n  pass"), _reply(code="y = 2")])
    r = review_code(llm, REQ, "m")
    _check("syntax-retry: 2 calls", len(llm.calls) == 2)
    _check("syntax-retry: message names SyntaxError", "SyntaxError" in llm.calls[1][-1].content)
    _check("syntax-retry: valid script kept", "y = 2" in r.corrected_code and r.syntax_error == "")


def test_syntax_error_twice_warns():
    llm = FakeLLM([_reply(code="def f(:\n  pass"), _reply(code="def g(:\n  pass")])
    r = review_code(llm, REQ, "m")
    _check("syntax-twice: 2 calls", len(llm.calls) == 2)
    _check("syntax-twice: script kept, error named", "def g(:" in r.corrected_code and "SyntaxError" in r.syntax_error, r.syntax_error)


def test_bash_syntax_check():
    llm = FakeLLM([_reply(code="if then fi ("), _reply(code="echo hi")])
    r = review_code(llm, CodeReviewRequest(code="echo hi", language="bash"), "m")
    _check("bash: broken script retried", len(llm.calls) == 2 and "echo hi" in r.corrected_code)


def test_prompt_requires_py310():
    sysmsg = build_review_messages(REQ)[0].content
    _check("prompt: Python 3.10", "Python 3.10" in sysmsg)


def test_call_failure_is_an_error_review():
    r = review_code(RaisingLLM(), REQ, "m")
    _check("call failure: error set, no raise", bool(r.error) and "boom" in r.error, r.error)


def test_header_added():
    r = review_code(FakeLLM([_reply()]), REQ, "my-model")
    head = r.corrected_code.split("\n")[0]
    _check("header: start", r.corrected_code.startswith("# Generated by Code Review"))
    _check("header: model and check before use", "my-model" in head and "check before use" in head, head)


def test_key_depends_on_context():
    a = CodeReviewRequest(code="c", earlier_code="e1")
    b = CodeReviewRequest(code="c", earlier_code="e2")
    _check("key: earlier_code matters", review_key(a, "m") != review_key(b, "m"))
    _check("key: model matters", review_key(a, "m") != review_key(a, "n"))
    _check("key: identical same", review_key(a, "m") == review_key(CodeReviewRequest(code="c", earlier_code="e1"), "m"))


def test_language_in_prompt():
    msgs = build_review_messages(CodeReviewRequest(code="echo 1", language="bash"))
    _check("language: user message", "LANGUAGE: bash" in msgs[1].content)
    _check("language: same language rule", "in the same language" in msgs[0].content)


def test_oversize_code_clipped():
    msgs = build_review_messages(CodeReviewRequest(code="x" * 50_000))
    user = msgs[1].content
    _check("clip: marker", "characters omitted" in user)
    _check("clip: size bounded", len(user) < 40_000 + 2_000, str(len(user)))


def test_prompt_checklist_order():
    s = build_review_messages(REQ)[0].content
    idx = [s.find(k) for k in ("BUGS", "MISMATCHES", "UNITS AND CONSTANTS", "SCIENCE", "PORTABILITY")]
    _check("checklist order", all(i >= 0 for i in idx) and idx == sorted(idx), str(idx))
    _check("earlier steps and always", "earlier steps" in s and "always" in s)


def test_roundtrip_and_list_content():
    r = review_code(FakeLLM([_reply()]), REQ, "m")
    r2 = CodeReview.from_dict(json.loads(json.dumps(r.to_dict())))
    _check("to_dict/from_dict", r2 == r)
    llm = FakeLLM([[{"type": "text", "text": _reply()}]])
    _check("list content joined", review_code(llm, REQ, "m").corrected_code != "")


def run_all() -> int:
    for name, fn in list(globals().items()):
        if name.startswith("test_") and callable(fn):
            print(name)
            fn()
    print("\n" + "=" * 60)
    print(f"Results: {len(_PASSED)} passed, {len(_FAILED)} failed")
    print("=" * 60)
    for name, detail in _FAILED:
        print(f"  ✗ {name}: {detail}")
    return 1 if _FAILED else 0


if __name__ == "__main__":
    sys.exit(run_all())
