def _jobs_reset():
    jobs._clear_for_tests()
    os.environ["BIOMENTIS_RUN_DIR"] = tempfile.mkdtemp(prefix="cr_runs_")


def _factory(calls: list, reply=None):
    def make(model):
        calls.append(model)
        return FakeLLM([reply or _reply()])
    return make


def _req(**kw):
    return CodeReviewRequest(code=kw.pop("code", "print(1)"), **kw)


